-- BG-1.11 reviewed relationship contract. OPERATOR RUN ONLY, NON-PRODUCTION.
-- Does not read business records or alter silver_clean/public tables.
-- Set bg111.environment, bg111.target_database and bg111.confirm_write first.
BEGIN READ WRITE;
SET LOCAL statement_timeout = '10s';
SET LOCAL lock_timeout = '2s';
SET LOCAL search_path = pg_catalog, public;
DO $guard$
BEGIN
  IF current_setting('bg111.environment', true) IS NULL
     OR current_setting('bg111.environment', true) NOT IN ('local', 'staging')
     OR current_setting('bg111.target_database', true) IS DISTINCT FROM current_database()
     OR current_setting('bg111.confirm_write', true) IS DISTINCT FROM 'I_CONFIRM_NON_PRODUCTION' THEN
    RAISE EXCEPTION 'BG111 installation requires explicit non-production environment, exact database and write confirmation';
  END IF;
  IF to_regclass('public.master_categories') IS NULL
     OR to_regclass('public.product_category_master') IS NULL
     OR to_regclass('public.users') IS NULL
     OR to_regclass('public.category_mapping_history') IS NULL
     OR to_regclass('public.platform_category_mapping') IS NULL
     OR to_regclass('public.category_mapping_synonyms') IS NULL THEN
    RAISE EXCEPTION 'Required existing public catalog/user/audit tables are missing';
  END IF;
  IF EXISTS (
    SELECT 1 FROM (VALUES ('master_categories'), ('product_category_master'), ('users')) AS required(name)
    WHERE NOT EXISTS (
      SELECT 1 FROM pg_attribute a
      JOIN pg_constraint c ON c.conrelid=a.attrelid AND c.contype='p' AND c.conkey=ARRAY[a.attnum]::smallint[]
      WHERE a.attrelid=to_regclass('public.' || required.name)
        AND a.attname='id' AND a.atttypid='integer'::regtype AND a.attnotnull AND NOT a.attisdropped
    )
  ) THEN
    RAISE EXCEPTION 'Existing public IDs must be integer primary keys; resolve schema drift first';
  END IF;
END
$guard$;
CREATE SCHEMA IF NOT EXISTS category_mapping;
CREATE TABLE IF NOT EXISTS category_mapping.business_product_category_mappings (
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  business_category_id integer NOT NULL,
  business_subcategory_id integer NOT NULL,
  product_category_id integer NOT NULL,
  mapping_type varchar(40) NOT NULL DEFAULT 'carries_products',
  status varchar(30) NOT NULL DEFAULT 'APPROVED',
  approved_by_user_id integer NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT pk_bpcm PRIMARY KEY (id),
  CONSTRAINT uq_bpcm_relationship UNIQUE
    (business_category_id, business_subcategory_id, product_category_id, mapping_type),
  CONSTRAINT ck_bpcm_type CHECK (mapping_type = 'carries_products'),
  CONSTRAINT ck_bpcm_status CHECK (status = 'APPROVED'),
  CONSTRAINT fk_bpcm_business FOREIGN KEY (business_category_id) REFERENCES public.master_categories(id) ON DELETE RESTRICT,
  CONSTRAINT fk_bpcm_subcategory FOREIGN KEY (business_subcategory_id) REFERENCES public.master_categories(id) ON DELETE RESTRICT,
  CONSTRAINT fk_bpcm_product FOREIGN KEY (product_category_id) REFERENCES public.product_category_master(id) ON DELETE RESTRICT,
  CONSTRAINT fk_bpcm_approver FOREIGN KEY (approved_by_user_id) REFERENCES public.users(id) ON DELETE RESTRICT
);
-- Fail rather than silently adopting an existing table with a different shape.
DO $shape$
DECLARE actual text[];
BEGIN
  SELECT array_agg(a.attname || ':' || format_type(a.atttypid,a.atttypmod) || ':' || a.attnotnull::text ORDER BY a.attnum)
  INTO actual FROM pg_attribute a
  WHERE a.attrelid='category_mapping.business_product_category_mappings'::regclass
    AND a.attnum>0 AND NOT a.attisdropped;
  IF actual IS DISTINCT FROM ARRAY[
    'id:bigint:true', 'business_category_id:integer:true', 'business_subcategory_id:integer:true',
    'product_category_id:integer:true', 'mapping_type:character varying(40):true',
    'status:character varying(30):true', 'approved_by_user_id:integer:true',
    'created_at:timestamp with time zone:true'] THEN
    RAISE EXCEPTION 'Existing relationship table has an incompatible column contract';
  END IF;
  IF (SELECT count(*) FROM pg_constraint WHERE conrelid='category_mapping.business_product_category_mappings'::regclass
      AND conname IN ('pk_bpcm','uq_bpcm_relationship','ck_bpcm_type','ck_bpcm_status',
                      'fk_bpcm_business','fk_bpcm_subcategory','fk_bpcm_product','fk_bpcm_approver')
      AND convalidated) <> 8 THEN
    RAISE EXCEPTION 'Existing relationship table lacks required validated constraints';
  END IF;
  IF EXISTS (
    SELECT 1 FROM (VALUES
      ('pk_bpcm','p',ARRAY[1]::smallint[],NULL::regclass),
      ('uq_bpcm_relationship','u',ARRAY[2,3,4,5]::smallint[],NULL::regclass),
      ('fk_bpcm_business','f',ARRAY[2]::smallint[],'public.master_categories'::regclass),
      ('fk_bpcm_subcategory','f',ARRAY[3]::smallint[],'public.master_categories'::regclass),
      ('fk_bpcm_product','f',ARRAY[4]::smallint[],'public.product_category_master'::regclass),
      ('fk_bpcm_approver','f',ARRAY[7]::smallint[],'public.users'::regclass)
    ) AS expected(name,kind,keys,referenced)
    WHERE NOT EXISTS (
      SELECT 1 FROM pg_constraint c
      WHERE c.conrelid='category_mapping.business_product_category_mappings'::regclass
        AND c.conname=expected.name AND c.contype::text=expected.kind AND c.conkey=expected.keys
        AND NOT c.condeferrable AND c.convalidated
        AND (expected.kind<>'f' OR (c.confrelid=expected.referenced AND c.confdeltype='r'
          AND c.confkey=ARRAY[(SELECT attnum FROM pg_attribute WHERE attrelid=expected.referenced AND attname='id')]::smallint[]))
    )
  ) THEN RAISE EXCEPTION 'Existing relationship key/FK definitions are incompatible'; END IF;
  IF EXISTS (
    SELECT 1 FROM (VALUES ('ck_bpcm_type','mapping_type=''carries_products'''),
                         ('ck_bpcm_status','status=''APPROVED''')) AS expected(name,expression)
    WHERE NOT EXISTS (
      SELECT 1 FROM pg_constraint c
      WHERE c.conrelid='category_mapping.business_product_category_mappings'::regclass
        AND c.conname=expected.name AND c.contype='c' AND c.convalidated
        AND regexp_replace(replace(pg_get_expr(c.conbin,c.conrelid),'::text',''),'[[:space:]()]','','g')=expected.expression
    )
  ) THEN RAISE EXCEPTION 'Existing relationship status/type checks are incompatible'; END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_attribute WHERE attrelid='category_mapping.business_product_category_mappings'::regclass
                 AND attname='id' AND attidentity IN ('a','d')) THEN
    RAISE EXCEPTION 'Relationship identity generation is missing';
  END IF;
END
$shape$;
